typedef enum {
    Pos_Pid, /*位置式PID*/
    Inc_Pid  /*增量式PID*/
} Pid_Mode;

typedef struct
{
    Pid_Mode       Mode;
    float          Kp, Ki, Kd;
    float          Max_Out, Max_Iout, Min_Out, Min_Iout;
    volatile float Exp, Real;
    volatile float Pout, Iout, Dout, Tout;
    volatile float Err[3];
} Pid_t;

